class Client {
 cookies=new Map();
 async request(route, options={}, params={}) {
  const url=new URL('index.php',base);url.search=new URLSearchParams({r:route,...params});
  const response=await fetch(url,{...options,redirect:'manual',headers:{...options.headers,Cookie:[...this.cookies].map(([key,value])=>key+'='+value).join('; ')}});
  for(const cookie of response.headers.getSetCookie()){const [pair]=cookie.split(';');const at=pair.indexOf('=');this.cookies.set(pair.slice(0,at),pair.slice(at+1));}
  return response;
 }
 async html(route='feed',params={}) {return (await this.request(route,{},params)).text();}
 async post(route,action,fields={},files=[],params={}) {
  const body=new FormData();body.set('csrf',this.csrf);body.set('action',action);
  for(const [key,value] of Object.entries(fields)) body.set(key,String(value));
  for(const [key,name,type] of files) body.append(key,new Blob([await readFile(path.join(directory,name))],{type}),name);
  return this.request(route,{method:'POST',body},params);
 }
 async login(name) {
  this.csrf=/name="csrf" value="([a-f0-9]+)"/.exec(await this.html('login'))?.[1];
  assert.equal((await this.post('login','login',{identity:name,password})).status,303);
  this.csrf=/name="csrf" value="([a-f0-9]+)"/.exec(await this.html())?.[1];
 }
}
