CREATE TABLE IF NOT EXISTS f_media (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 user_id BIGINT UNSIGNED NOT NULL,
 post_id BIGINT UNSIGNED NULL,
 slot VARCHAR(10) NOT NULL,
 filename VARCHAR(80) NOT NULL UNIQUE,
 original_name VARCHAR(190) NOT NULL,
 mime VARCHAR(80) NOT NULL,
 bytes BIGINT UNSIGNED NOT NULL,
 created_at DATETIME NOT NULL,
 FOREIGN KEY (user_id) REFERENCES f_users(id) ON DELETE CASCADE,
 FOREIGN KEY (post_id) REFERENCES f_posts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS f_profiles (
 user_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 links TEXT NOT NULL,
 avatar_id BIGINT UNSIGNED NULL,
 header_id BIGINT UNSIGNED NULL,
 newsletter INTEGER NOT NULL DEFAULT 0,
 consent_at DATETIME NULL,
 unsubscribe_hash VARCHAR(64) NOT NULL DEFAULT '',
 FOREIGN KEY (user_id) REFERENCES f_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS f_post_links (
 post_id BIGINT UNSIGNED NOT NULL PRIMARY KEY,
 url VARCHAR(2048) NOT NULL,
 title VARCHAR(300) NOT NULL,
 description TEXT NOT NULL,
 FOREIGN KEY (post_id) REFERENCES f_posts(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS f_documents (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 slug VARCHAR(80) NOT NULL UNIQUE,
 title_de VARCHAR(190) NOT NULL,
 title_en VARCHAR(190) NOT NULL,
 body_de TEXT NOT NULL,
 body_en TEXT NOT NULL,
 published INTEGER NOT NULL DEFAULT 0,
 updated_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS f_campaigns (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 subject VARCHAR(190) NOT NULL,
 body TEXT NOT NULL,
 created_at DATETIME NOT NULL,
 actor_id BIGINT UNSIGNED NOT NULL,
 FOREIGN KEY (actor_id) REFERENCES f_users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS f_mail_queue (
 id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
 campaign_id BIGINT UNSIGNED NOT NULL,
 user_id BIGINT UNSIGNED NOT NULL,
 status VARCHAR(10) NOT NULL DEFAULT 'pending',
 UNIQUE (campaign_id,user_id),
 FOREIGN KEY (campaign_id) REFERENCES f_campaigns(id) ON DELETE CASCADE,
 FOREIGN KEY (user_id) REFERENCES f_users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
